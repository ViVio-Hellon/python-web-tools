"""PalletMaster の 記号 から、もとの記号(型の名前)を取り出す。

【記号の書き方が変わった(2026-10、Access の PalletMaster)】
台・枚の行の記号に、品種と補足が付くようになった。

    前:  C1                 → いま: C1 ﾊﾟﾚｯﾄ台
         強度UP             →       強度UP ﾊﾟﾚｯﾄ台 薄板用5x10
         A8                 →       A8 ﾊﾟﾚｯﾄ台 標準5x10(新5x10)
         (空)               →        ﾊﾟﾚｯﾄ台 マトリックス
         EXﾀｲﾄ              →       EXﾀｲﾄ ﾊﾟﾚｯﾄ台 ﾊﾟﾚｯﾄ台 熱処理輸出

**「ﾊﾟﾚｯﾄ台」「ﾊﾟﾚｯﾄ蓋」より前が、もとの記号。** 組の行(ﾊﾟﾚｯﾄ台・ﾊﾟﾚｯﾄ蓋が付かない)は
そのまま使う。前の書き方の記号(印が無い)もそのまま ── 入れ替えていない端末でも同じに動く。

記号を**型として**見るところ(品名・帳票に出す記号、5×10 の強度UP の見分け、
固定の適合範囲・桁数・脚数を引く鍵)はこれを通す。一覧に出す記号・行の見分けは、
マスタの記号のまま使う(書いてあるとおりに見せる・押した行と同じ行を引く)。
"""
from __future__ import annotations

from typing import Any

# 品種の印。半角カナで書いてある。全角で打たれても同じに扱う
KIND_MARKS = ("ﾊﾟﾚｯﾄ台", "ﾊﾟﾚｯﾄ蓋", "パレット台", "パレット蓋")


def base_symbol(symbol: Any) -> str:
    """もとの記号。品種の印(ﾊﾟﾚｯﾄ台/ﾊﾟﾚｯﾄ蓋)より前を、前後の空白を除いて返す。印が無ければ全体。"""
    text = str(symbol or "")
    cuts = [text.find(mark) for mark in KIND_MARKS if mark in text]
    if cuts:
        text = text[:min(cuts)]
    return text.strip()
