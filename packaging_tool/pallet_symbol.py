"""PalletMaster の 記号 から、もとの記号(型の名前)を取り出す。一覧に出す「記号(品種・備考)」も作る。

【記号は記号のまま(VER4.8.51 からの決め)】
現場の声:「記号は記号として扱うべき。記号は元に戻す。資材選定のリストには、記号・備考・
台はﾊﾟﾚｯﾄ台・枚はﾊﾟﾚｯﾄ蓋 を混ぜたものを記号の代わりに表示したい」。
マスタの記号は元の型の名前(C1・強度UP・EXﾀｲﾄ …)に戻し、つなげた見せ方は一覧でだけ作る(`list_label`)。

【いっとき記号の書き方が変わっていた(2026-10、Access の PalletMaster)】
台・枚の行の記号に、品種と補足が付いていた。マスタを戻す前・戻しそこねた行のために、
`base_symbol` で読む所はそのまま残す(印が無ければ何もしない)。

    前:  C1                 → いま: C1 ﾊﾟﾚｯﾄ台
         強度UP             →       強度UP ﾊﾟﾚｯﾄ台 薄板用5x10
         A8                 →       A8 ﾊﾟﾚｯﾄ台 標準5x10(新5x10)
         (空)               →        ﾊﾟﾚｯﾄ台 マトリックス
         EXﾀｲﾄ              →       EXﾀｲﾄ ﾊﾟﾚｯﾄ台 ﾊﾟﾚｯﾄ台 熱処理輸出

**「ﾊﾟﾚｯﾄ台」「ﾊﾟﾚｯﾄ蓋」より前が、もとの記号。** 組の行(ﾊﾟﾚｯﾄ台・ﾊﾟﾚｯﾄ蓋が付かない)は
そのまま使う。前の書き方の記号(印が無い)もそのまま ── 入れ替えていない端末でも同じに動く。

記号を**型として**見るところ(品名・帳票に出す記号、5×10 の強度UP の見分け、
固定の適合範囲・桁数・脚数を引く鍵)はこれを通す。一覧に出す記号・行の見分けは、
マスタの記号のまま使う(書いてあるとおりに見せる・押した行と同じ行を引く)。
"""
from __future__ import annotations

from typing import Any

# 品種の印。半角カナで書いてある。全角で打たれても同じに扱う
KIND_MARKS = ("ﾊﾟﾚｯﾄ台", "ﾊﾟﾚｯﾄ蓋", "パレット台", "パレット蓋")


# 一覧に出す品種の印(単位から決める)。マスタの記号には混ぜない
KIND_BY_UNIT = {"台": "ﾊﾟﾚｯﾄ台", "枚": "ﾊﾟﾚｯﾄ蓋"}


def list_label(symbol: Any, unit: Any, remark: Any) -> str:
    """資材選択の一覧に出す「記号(品種・備考)」。**表示だけ**のもの。

    現場の声:「記号は記号として扱うべき。資材選定時のリストには、記号・備考・台はﾊﾟﾚｯﾄ台・枚はﾊﾟﾚｯﾄ蓋を
    混ぜたものを記号の代わりに表示したい」。マスタの記号は元の型の名前に戻し、
    蓋とパレット台の見分け・補足は**一覧でだけ**つなげて見せる(品名・帳票・判定には使わない)。

        記号 C1・単位 台・備考 空        → 「C1 ﾊﾟﾚｯﾄ台」
        記号 EXﾀｲﾄ・単位 枚・備考 熱処理輸出 → 「EXﾀｲﾄ ﾊﾟﾚｯﾄ蓋 熱処理輸出」
        記号 空・単位 台・備考 マトリックス   → 「ﾊﾟﾚｯﾄ台 マトリックス」
        記号 脚75・単位 組                → 「脚75」(組は品種を付けない)

    記号にまだ品種の印が混ざっていても(戻す前のマスタ)、もとの記号だけを使う。
    備考が記号と同じなら重ねて出さない。
    """
    base = base_symbol(symbol)
    kind = KIND_BY_UNIT.get(str(unit or "").strip(), "")
    note = str(remark or "").strip()
    if note == base:
        note = ""
    return " ".join(part for part in (base, kind, note) if part)


def base_symbol(symbol: Any) -> str:
    """もとの記号。品種の印(ﾊﾟﾚｯﾄ台/ﾊﾟﾚｯﾄ蓋)より前を、前後の空白を除いて返す。印が無ければ全体。"""
    text = str(symbol or "")
    cuts = [text.find(mark) for mark in KIND_MARKS if mark in text]
    if cuts:
        text = text[:min(cuts)]
    return text.strip()
