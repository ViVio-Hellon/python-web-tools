"""パレット適合閾値 ── 基準表をプログラムから表へ出す

【なぜ表に出したのか】
「幅1000のパレットには幅941〜990の製品が載る」「丈2700なら脚は4本」
という数値は、社内のタイトパレット選定基準表そのものです。基準が
変われば数値も変わります。ところがこれまでは `pallet_service.py` の中に
Pythonの表として直接書かれていて、**1つ直すのにプログラムの改修と
配り直しが要る**状態でした。資材課が自分で直せる場所へ移します。

移植元(VBA)は同じ判断を先に済ませていて、`PalletThresholdMaster.accdb`
という別ファイルに7つの表を持っています。**その表名・列名・データを
そのまま写して**あります。名前を変えると、あちらの生成ツールが作った
ファイルを取り込めなくなります。

    VBA                                   -> Python
    ----------------------------------------------------------------
    PalletThresholdLoad / PT_LoadBand       -> load
    PT_ChkBand                               -> _check_band
    PT_Lookup                                 -> _lookup
    PT_DakeMin / PT_DakeMax                    -> Thresholds.dake_min / dake_max
    PT_HabaMin / PT_HabaMax                     -> Thresholds.haba_min / haba_max
    PT_Ashi / PT_Keta                            -> Thresholds.ashi / keta
    PT_CreateThresholdDB のデータ投入部            -> SEED / seed

【置き場所は梱包資材マスタと同じ1つ】
VBAは閾値だけ別ファイルにしていますが、Python側のマスタ編集は
「取り込み元(共有フォルダの梱包資材マスタ)ただ1つに書いて、その表を
取り込み直す」設計です(`master_admin` の冒頭)。書き先を2つに増やすと
その設計が崩れるので、アクセス権限と同じく**梱包資材マスタに同居**
させます。表と列とデータは移植元のままです。

【読めなければ計算しない(VBA 案X と同じ)】
帯に穴があると、その寸法だけ「該当なし」になります。黙って一部だけ
計算すると、**計算したのに間違っている行**が混じって、どれが正しいのか
分からなくなります。`load()` は連続性を確かめ、崩れていれば
`ThresholdError` を投げて呼び出し側に中断させます。
"""
from __future__ import annotations

import sqlite3
from dataclasses import dataclass
from typing import Any, Iterable, Optional

from .logging_utils import get_logger

log = get_logger("pallet_threshold")

# 帯に当たらなかったときの値(VBA `PT_Lookup` と同じ)。
# **0やNoneにしません。** 0は「幅0まで載る」と読めてしまい、
# 該当なしと区別がつかなくなります
NO_HIT = -999999

# 帯が覆うべき上端。最終行の入力最大値がこれでなければ穴があるとみなす
BAND_TOP = 999999

# 帯の表(入力の範囲 → 値)
BAND_TABLES: tuple[str, ...] = (
    "PalletDakeThreshold", "PalletHabaThreshold",
    "PalletAshiThreshold", "PalletKetaThreshold",
)

# 固定適合の表(鍵 → 範囲)
KEY_TABLES: tuple[str, ...] = (
    "PalletSymbolMaster", "PalletIndustryMaster", "PalletComboMaster",
)

TABLES: tuple[str, ...] = BAND_TABLES + KEY_TABLES

# 帯の表ごとに、どの列が「下の値」「上の値」か。
# 脚数・桁数は1つの値しか持たないので、上下に同じ列を割り当てる
# (VBA `PT_LoadBand` の呼び出しがそうしている)
_BAND_VALUE_COLUMNS: dict[str, tuple[str, str]] = {
    "PalletDakeThreshold": ("適合最小値", "適合最大値"),
    "PalletHabaThreshold": ("適合最小値", "適合最大値"),
    "PalletAshiThreshold": ("脚数", "脚数"),
    "PalletKetaThreshold": ("桁数", "桁数"),
}


class ThresholdError(Exception):
    """閾値が読めない/帯が繋がっていない。**計算を中断させるための例外。**"""


@dataclass(frozen=True)
class Band:
    """帯1本。`in_min`〜`in_max` に入る寸法なら `lo`/`hi` を返す。"""

    in_min: int
    in_max: int
    lo: int
    hi: int


def _int(value: Any) -> int:
    """表の値を整数に。空欄や読めない値は0(帯の検査がそれを捕まえる)。"""
    if value is None:
        return 0
    try:
        return int(float(str(value).strip() or 0))
    except (ValueError, OverflowError):
        return 0


def rows(conn: sqlite3.Connection, table: str) -> list[sqlite3.Row]:
    """その表の**有効な行だけ**を並び順で返す。

    `WHERE 有効<>0` は移植元のとおり ── 行を消さずに外せるようにする
    ためです。並びは帯の表が `入力最小値`、鍵の表が `並び順`。
    どちらも `ID` を副えているのは、**同じ値が並んだときに順序が
    毎回変わらないようにする**ためです(移植元のデータは並び順が全行0で、
    Accessの物理順に頼っていました)。
    """
    order = "入力最小値" if table in BAND_TABLES else "並び順"
    try:
        return list(conn.execute(
            f"SELECT * FROM [{table}] WHERE [有効] <> 0 "
            f"ORDER BY [{order}], [ID]"))
    except sqlite3.Error as exc:
        raise ThresholdError(f"{table} を読めません: {exc}") from exc


def _load_band(conn: sqlite3.Connection, table: str) -> tuple[Band, ...]:
    lo_col, hi_col = _BAND_VALUE_COLUMNS[table]
    found = rows(conn, table)
    if not found:
        raise ThresholdError(f"{table} に有効な行がありません")
    return tuple(
        Band(in_min=_int(r["入力最小値"]), in_max=_int(r["入力最大値"]),
             lo=_int(r[lo_col]), hi=_int(r[hi_col]))
        for r in found)


def _check_band(table: str, bands: Iterable[Band]) -> None:
    """帯が 0〜999999 まで隙間なく続いているか(VBA `PT_ChkBand`)。

    穴があるとその寸法だけ判定できません。**どこで切れているかを
    言います** ── 「読み込みに失敗しました」だけでは、どの行を直せば
    よいのか分かりません。
    """
    expect = 0
    last = -1
    for index, band in enumerate(bands, start=1):
        if band.in_min != expect:
            raise ThresholdError(
                f"{table} の帯が繋がっていません。{index}行目の入力最小値が "
                f"{band.in_min} ですが、{expect} から続く必要があります")
        if band.in_min > band.in_max:
            raise ThresholdError(
                f"{table} の{index}行目で入力最小値({band.in_min})が"
                f"入力最大値({band.in_max})を超えています")
        expect = band.in_max + 1
        last = band.in_max
    if last != BAND_TOP:
        raise ThresholdError(
            f"{table} の最終行の入力最大値が {last} です。"
            f"{BAND_TOP} まで覆う必要があります"
            f"(そこまでの寸法が来ても判定できるようにするため)")


def _lookup(value: int, bands: tuple[Band, ...], *, upper: bool) -> int:
    """帯を引く(VBA `PT_Lookup`)。当たらなければ `NO_HIT`。"""
    for band in bands:
        if band.in_min <= value <= band.in_max:
            return band.hi if upper else band.lo
    return NO_HIT


@dataclass(frozen=True)
class Thresholds:
    """読み込んで検査を通った帯ひとそろい。

    ここまで来ていれば 0〜999999 は必ずどれかの帯に当たります。
    `NO_HIT` が返るのは、範囲の外(負の値や999999超)を渡したときだけです。
    """

    dake: tuple[Band, ...]
    haba: tuple[Band, ...]
    ashi_bands: tuple[Band, ...]
    keta_bands: tuple[Band, ...]

    def dake_min(self, dake: int) -> int:
        """丈適合min(VBA `PT_DakeMin`)。`dake_max` と必ず対で使うこと。"""
        return _lookup(dake, self.dake, upper=False)

    def dake_max(self, dake: int) -> int:
        return _lookup(dake, self.dake, upper=True)

    def haba_min(self, haba: int) -> int:
        """巾適合min(VBA `PT_HabaMin`)。`haba_max` と必ず対で使うこと。"""
        return _lookup(haba, self.haba, upper=False)

    def haba_max(self, haba: int) -> int:
        return _lookup(haba, self.haba, upper=True)

    def ashi(self, dake: int) -> int:
        """脚の本数(VBA `PT_Ashi`)。"""
        return _lookup(dake, self.ashi_bands, upper=False)

    def keta(self, haba: int) -> int:
        """桁の本数(VBA `PT_Keta`)。"""
        return _lookup(haba, self.keta_bands, upper=False)


def load(conn: sqlite3.Connection) -> Thresholds:
    """4つの帯を読んで検査する(VBA `PalletThresholdLoad`)。

    移植元は読み込んだ結果をモジュール変数にキャッシュし、設定画面で
    保存するたびに `PalletThresholdCacheClear` で捨てていました。
    Python版はキャッシュを持ちません ── 呼ぶのは再計算のときだけで、
    手元のSQLiteを4回読むだけです。**捨て忘れて古い値で計算する**
    という失敗の余地を残さないほうが確かです。
    """
    got = Thresholds(
        dake=_load_band(conn, "PalletDakeThreshold"),
        haba=_load_band(conn, "PalletHabaThreshold"),
        ashi_bands=_load_band(conn, "PalletAshiThreshold"),
        keta_bands=_load_band(conn, "PalletKetaThreshold"),
    )
    _check_band("PalletDakeThreshold", got.dake)
    _check_band("PalletHabaThreshold", got.haba)
    _check_band("PalletAshiThreshold", got.ashi_bands)
    _check_band("PalletKetaThreshold", got.keta_bands)
    log.info("閾値を読みました 丈=%s帯 幅=%s帯 脚=%s帯 桁=%s帯",
             len(got.dake), len(got.haba),
             len(got.ashi_bands), len(got.keta_bands))
    return got


