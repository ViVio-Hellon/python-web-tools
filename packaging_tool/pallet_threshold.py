def seed(conn: sqlite3.Connection, table: Optional[str] = None) -> dict[str, int]:
    """まだ1行も無い表に基準表を入れる。**入っている表には触らない。**

    起動のたびに通ります(`db.apply_schema` の直後)。空のときだけ
    入れるので、資材課が直した値を毎回書き戻してしまうことはありません。

    空のまま放っておけない理由は、閾値の表が**空だと計算が止まる**
    からです(帯が0〜999999を覆えない)。他のマスタと違って「無ければ
    その機能を使わない」で済ませられません。
    """
    filled: dict[str, int] = {}
    targets = (table,) if table else tuple(SEED)
    for name in targets:
        seed_rows = SEED.get(name)
        if not seed_rows:
            continue
        try:
            count = conn.execute(
                f"SELECT COUNT(*) FROM [{name}]").fetchone()[0]
        except sqlite3.Error as exc:             # pragma: no cover - 通常は無い
            log.warning("%s を数えられません: %s", name, exc)
            continue
        if count:
            continue
        columns = list(seed_rows[0])
        col_list = ", ".join(f"[{c}]" for c in columns)
        marks = ", ".join("?" for _ in columns)
        with conn:
            conn.executemany(
                f"INSERT INTO [{name}] ({col_list}) VALUES ({marks})",
                [tuple(row[c] for c in columns) for row in seed_rows])
        filled[name] = len(seed_rows)
        log.info("%s に基準表の初期値を%s件入れました", name, len(seed_rows))
    return filled
